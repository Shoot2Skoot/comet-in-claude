// Every line a state can show; `alt` is the version, already in range.
export function linesFor(mood: Mood, tool: ToolKind, alt: number, alien: string): readonly string[] {
  if (mood === 'tool') return TOOL_LINES[tool]
  if (mood === 'think') return THINK_LINES
  if (mood === 'idle') return (IDLE_LINES[alt] ?? IDLE_LINES[0] ?? []).map(line => line.replace('{alien}', alien))
  return MOOD_LINES[mood]
}

// The line a state shows: `say` is the roll made when the state began.
export function lineFor(mood: Mood, tool: ToolKind, alt: number, say: number, alien: string): string {
  const lines = linesFor(mood, tool, alt, alien)
  return lines[Math.abs(Math.floor(say)) % lines.length] ?? lines[0] ?? ''
}
